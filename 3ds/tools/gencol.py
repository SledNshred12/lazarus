import json
from PIL import Image
OUT='/home/claude/lazarus/3ds'; SC=0.6
meta=json.load(open('/home/claude/sprites/col/meta.json'))
KIDX={'hall':0,'house':1,'farm':2,'well':3,'clinic':4,'san':5,'vacc':6}
NAMES=['Greenhollow','Marrowfield','Ashbrook','Sunderland','Pallid Ridge','Fenwick Reach','Thistledown','Mossgate','Cinder Vale','Larkspur']
KINDN={'farm':'Farming Village','med':'Medical Town','fort':'Fortress Camp','river':'River Town'}
BIOME={'plain':'Dust flats','desert':'Desert','swamp':'Swamp','ruins':'City ruins','snow':'Frozen north'}
h=['/* generated by tools/gencol.py from the game\'s own rival colonies */','#pragma once',
   'typedef struct { short k, x, y, r; float hp, den; short loot; char wall, gate; short sx, sy, fx, fy, cx, cy; } EB;',
   'typedef struct { const char *name, *kind, *biome; int tier, walled, n, loot; const EB *b; } ColDef;']
defs=[]
import os
for t,m in enumerate(meta):
    # background
    bg=Image.open(f'/home/claude/sprites/col/bg_{t}.png').convert('RGBA'); bg=bg.resize((round(480*SC),round(400*SC)),Image.LANCZOS)
    bg.save(f'{OUT}/gfx/colbg_{t}.png'); open(f'{OUT}/gfx/colbg_{t}.t3s','w').write('-f rgba -z auto\ncolbg_%d.png\n'%t)
    lines=[]; rows=[]
    for j,b in enumerate(m['bld']):
        pos=[]
        for st in range(2):
            s=b['sp'][st]
            if s:
                im=Image.open(f'/home/claude/sprites/col/b_{t}_{j}_{st}.png').convert('RGBA')
                im=im.resize((max(1,round(im.width*SC)),max(1,round(im.height*SC))),Image.LANCZOS)
                pos.append((round(s['x']*SC),round(s['y']*SC),im.width,im.height))
            else:
                im=Image.new('RGBA',(1,1),(0,0,0,0)); pos.append((0,0,1,1))
            nm=f'cb_{t}_{j}_{st}.png'; im.save(f'{OUT}/gfx/{nm}'); lines.append(nm)
        k=7 if b['wall'] else KIDX.get(b['k'],1)
        cx=pos[0][0]+pos[0][2]//2; cy=pos[0][1]+pos[0][3]//2
        rows.append('{%d,%d,%d,%d,%.1ff,%.2ff,%d,%d,%d,%d,%d,%d,%d,%d,%d}'%(k,round(b['x']),round(b['y']),round(b['r']),b['hp'],b['den'],b['loot'],b['wall'],b['gate'],pos[0][0],pos[0][1],pos[1][0],pos[1][1],cx,cy))
    open(f'{OUT}/gfx/colsp_{t}.t3s','w').write('--atlas -f rgba -z auto\n'+'\n'.join(lines)+'\n')
    h.append(f'static const EB COLB_{t}[{len(rows)}]={{'+','.join(rows)+'};')
    defs.append('{"%s","%s","%s",%d,%d,%d,%d,COLB_%d}'%(NAMES[t],KINDN[m['kind']],BIOME[m['biome']],t,1 if m['lay']=='walled' else 0,len(rows),m['loot'],t))
h.append('#define NCOLS %d'%len(meta)); h.append('static const ColDef COLS[NCOLS]={'+','.join(defs)+'};')
open(f'{OUT}/source/colonies.h','w').write('\n'.join(h)+'\n')
print(len(meta),'colonies', sum(len(m['bld']) for m in meta),'buildings')
